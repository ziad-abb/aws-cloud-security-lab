"""Sanitized Prowler summary for publishing.

Reads the CIS AWS 7.0 compliance CSVs of each Prowler run folder (e.g. reports/prowler/run1-baseline,
2-during, 3-after) and prints a Markdown summary: overall pass/fail, per CIS section, and the
requirements whose status changed between runs. No account ID, region, resource ID or ARN is printed.

Usage (repo root):
  python scripts/prowler_summary.py reports/prowler/run1-baseline reports/prowler/2-during reports/prowler/3-after > reports/prowler/summary.md
"""
import csv
import glob
import os
import sys
from collections import Counter, defaultdict


def find(cols, *names):
    for n in names:
        for c in cols:
            if c.upper() == n:
                return c
    for n in names:
        for c in cols:
            if n in c.upper():
                return c
    return None


def load(folder):
    files = glob.glob(os.path.join(folder, "compliance", "*cis_7.0_aws*.csv"))
    if not files:
        sys.exit(f"No CIS 7.0 compliance CSV in {folder}/compliance")
    with open(files[0], newline="", encoding="utf-8") as fh:
        rows = list(csv.DictReader(fh, delimiter=";"))
    cols = rows[0].keys()
    c_status = find(cols, "STATUS")
    c_req = find(cols, "REQUIREMENTS_ID")
    c_desc = find(cols, "REQUIREMENTS_DESCRIPTION")
    c_sec = find(cols, "REQUIREMENTS_ATTRIBUTES_SECTION")
    findings = Counter()
    sections = defaultdict(Counter)
    reqs = {}
    for r in rows:
        st = (r.get(c_status) or "").upper()
        if st not in ("PASS", "FAIL"):
            continue
        findings[st] += 1
        sections[r.get(c_sec) or "?"][st] += 1
        rid = r.get(c_req) or "?"
        prev = reqs.get(rid, ("PASS", (r.get(c_desc) or "")[:90]))
        reqs[rid] = ("FAIL" if st == "FAIL" or prev[0] == "FAIL" else "PASS", prev[1])
    return findings, sections, reqs


def pct(c):
    t = c["PASS"] + c["FAIL"]
    return f"{100 * c['PASS'] / t:.2f} %" if t else "-"


runs = [(os.path.basename(f.rstrip("/\\")), load(f)) for f in sys.argv[1:]]
print("# Prowler summary: CIS AWS Foundations 7.0 (sanitized)\n")
print("Generated by `scripts/prowler_summary.py`. Raw reports stay private (they contain account and resource IDs).\n")
print("## Overall (findings)\n")
print("| Run | Pass | Fail | Score |\n|---|---|---|---|")
for name, (f, _, _) in runs:
    print(f"| {name} | {f['PASS']} | {f['FAIL']} | {pct(f)} |")
print("\n## Requirements (a requirement fails if any resource fails it)\n")
print("| Run | Requirements passed | Requirements failed |\n|---|---|---|")
for name, (_, _, r) in runs:
    c = Counter(v[0] for v in r.values())
    print(f"| {name} | {c['PASS']} | {c['FAIL']} |")
print("\n## Failed findings by CIS section\n")
secs = sorted({s for _, (_, sc, _) in runs for s in sc})
print("| Section | " + " | ".join(n for n, _ in runs) + " |")
print("|---|" + "---|" * len(runs))
for s in secs:
    print(f"| {s} | " + " | ".join(str(sc[s]["FAIL"]) for _, (_, sc, _) in runs) + " |")
if len(runs) >= 2:
    (n1, (_, _, a)), (n2, (_, _, b)) = runs[-2], runs[-1]
    fixed = sorted(k for k in a if a[k][0] == "FAIL" and b.get(k, ("FAIL",))[0] == "PASS")
    broke = sorted(k for k in b if b[k][0] == "FAIL" and a.get(k, ("PASS",))[0] == "PASS")
    print(f"\n## Changes {n1} → {n2}\n")
    print(f"**Now passing ({len(fixed)}):**\n")
    for k in fixed:
        print(f"- {k}: {b[k][1]}")
    print(f"\n**Now failing ({len(broke)}):**\n")
    for k in broke:
        print(f"- {k}: {b[k][1]}")
